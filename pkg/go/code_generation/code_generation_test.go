func TestGenerateLiteral(t *testing.T) {
	t.Parallel()
	type args struct {
		value     reflect.Value
		importSet ImportSet
	}
	tests := []struct {
		name    string
		args    args
		want    string
		want1   ImportSet
		wantErr bool
	}{
		{
			name:  "bool true",
			args:  args{value: reflect.ValueOf(true)},
			want:  "true",
			want1: nil,
		},
		{
			name:  "string quoted",
			args:  args{value: reflect.ValueOf("hello")},
			want:  "\"hello\"",
			want1: nil,
		},
		{
			name:  "int literal",
			args:  args{value: reflect.ValueOf(int(42))},
			want:  "42",
			want1: nil,
		},
		{
			name:  "float32 NaN adds math import",
			args:  args{value: reflect.ValueOf(float32(math.NaN()))},
			want:  "math.NaN()",
			want1: ImportSet{"math": {}},
		},
		{
			name:  "complex128 with Inf real adds math import",
			args:  args{value: reflect.ValueOf(complex(math.Inf(1), 2))},
			want:  "complex(math.Inf(1), 2)",
			want1: ImportSet{"math": {}},
		},
		{
			name: "struct with non-zero fields and import path",
			args: args{value: reflect.ValueOf(localStruct{A: 1, B: "x"})},
			want: "code_generation.localStruct{\n    A: 1,\n    B: \"x\",\n}",
			want1: func() ImportSet {
				// Pkg path import is added by GenerateLiteral for structs from non-main packages
				pkgPath := reflect.TypeOf(localStruct{}).PkgPath()
				return ImportSet{pkgPath: {}}
			}(),
		},
		{
			name:  "nil func literal",
			args:  args{value: reflect.ValueOf((func())(nil))},
			want:  "nil",
			want1: nil,
		},
		{
			name:    "non-nil func returns error",
			args:    args{value: reflect.ValueOf(func() {})},
			wantErr: true,
		},
		{
			name:  "nil chan literal",
			args:  args{value: reflect.ValueOf((chan int)(nil))},
			want:  "nil",
			want1: nil,
		},
		{
			name:    "non-nil chan returns error",
			args:    args{value: reflect.ValueOf(make(chan int))},
			wantErr: true,
		},
		{
			name:  "interface kind quoted",
			args:  args{value: reflect.ValueOf(new(any)).Elem()}, // zero interface value
			want:  "\"<nil>\"",
			want1: nil,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			got, got1, err := GenerateLiteral(tt.args.value, tt.args.importSet)
			if (err != nil) != tt.wantErr {
				t.Fatalf("GenerateLiteral() error = %v, wantErr %v", err, tt.wantErr)
			}
			if err == nil {
				if got != tt.want {
					t.Errorf("GenerateLiteral() got = %q, want %q", got, tt.want)
				}
				if !reflect.DeepEqual(got1, tt.want1) {
					t.Errorf("GenerateLiteral() got1 = %v, want %v", got1, tt.want1)
				}
			}
		})
	}
}

